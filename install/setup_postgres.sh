# load configuration
RUNDIR=$(dirname $0)
source $RUNDIR/install.cfg

###############################################################################
# Configure PostgreSQL
###############################################################################
SQL="SELECT COUNT(1) FROM pg_catalog.pg_database WHERE datname = 'tippr';"
IS_DATABASE_CREATED=$(sudo -u postgres env LC_ALL=C psql -t -c "$SQL" | tr -d '[:space:]')

# Ensure the proper locale is generated and available. Prefer en_US.UTF-8 but
# tolerate variants like en_US.utf8 which PostgreSQL may expect.
if ! locale -a | grep -iq "en_US"; then
    echo "Generating en_US.UTF-8 locale..."
    apt-get update -y
    apt-get install -y locales || true
    locale-gen en_US.UTF-8 || true
    update-locale LANG=en_US.UTF-8 || true
fi

# Determine a locale string PostgreSQL will accept (try common variants).
LOCALE_NAME=""
for cand in "en_US.UTF-8" "en_US.utf8" "en_US.UTF8" "en_US"; do
    if locale -a | grep -iq "^${cand}$"; then
        LOCALE_NAME=$cand
        break
    fi
done

if [ "$IS_DATABASE_CREATED" != "1" ]; then
    # Try creating the DB specifying LC_COLLATE/LC_CTYPE if we detected a usable locale.
    if [ -n "$LOCALE_NAME" ]; then
        if sudo -u postgres env LC_ALL=C psql -c "CREATE DATABASE tippr WITH ENCODING = 'UTF8' TEMPLATE template0 LC_COLLATE='${LOCALE_NAME}' LC_CTYPE='${LOCALE_NAME}';" 2>/tmp/createdb.err; then
            echo "Database created with locale ${LOCALE_NAME}"
        else
            echo "Failed to create database with locale ${LOCALE_NAME}, retrying without explicit locale..."
            cat /tmp/createdb.err || true
                sudo -u postgres env LC_ALL=C psql -c "CREATE DATABASE tippr WITH ENCODING = 'UTF8' TEMPLATE template0;" || true
        fi
    else
          sudo -u postgres env LC_ALL=C psql -c "CREATE DATABASE tippr WITH ENCODING = 'UTF8' TEMPLATE template0;" || true
    fi
fi

# Create role if it doesn't exist
ROLE_EXISTS=$(sudo -u postgres env LC_ALL=C psql -t -c "SELECT 1 FROM pg_roles WHERE rolname='tippr';" | tr -d '[:space:]')
if [ "$ROLE_EXISTS" != "1" ]; then
     sudo -u postgres env LC_ALL=C psql -c "CREATE USER tippr;" || true
fi
# Set the password on every run so it follows $TIPPR_DB_PASSWORD (generated by
# install/tippr.sh). Pass it as a psql variable so :'pw' quotes it safely.
echo "ALTER USER tippr WITH PASSWORD :'pw';" | \
    sudo -u postgres env LC_ALL=C psql -v ON_ERROR_STOP=1 -v pw="$TIPPR_DB_PASSWORD"

# Ensure the tippr user owns the tippr database so it can create tables
sudo -u postgres env LC_ALL=C psql -c "ALTER DATABASE tippr OWNER TO tippr;" || true

# Grant privileges on the public schema to the tippr user (needed when the
# database owner is different or defaults are restrictive)
sudo -u postgres env LC_ALL=C psql tippr -c "GRANT ALL PRIVILEGES ON SCHEMA public TO tippr;" || true

# Each r2 process keeps a connection pool per database role (up to ~13
# connections). The web app, a dozen queue consumers and overlapping jobs
# exhaust the default limit of 100. ALTER SYSTEM only applies after a restart.
CURRENT_MAX_CONNECTIONS=$(sudo -u postgres env LC_ALL=C psql -Atc "SHOW max_connections;")
if [ "$CURRENT_MAX_CONNECTIONS" -lt 300 ]; then
    sudo -u postgres env LC_ALL=C psql -c "ALTER SYSTEM SET max_connections = 300;"
    systemctl restart postgresql
fi

# r2's SQL functions; on stdin, because the postgres user may not be able to
# read the checkout
sudo -u postgres env LC_ALL=C psql tippr -v ON_ERROR_STOP=1 \
    < "$RUNDIR/postgres_functions.sql"

# Who can connect: this server only, or on a backend (TIPPR_ROLE=backend,
# docs/SERVERS.md) its frontends too, on the address they reach it on, from
# their address range (TIPPR_FRONTEND_ALLOW), with the tippr password.
# PostgreSQL restarts only when this changes.
PG_CONF_DIR=$(dirname "$(sudo -u postgres env LC_ALL=C psql -Atc 'SHOW config_file;')")
PG_HBA=$(sudo -u postgres env LC_ALL=C psql -Atc 'SHOW hba_file;')
PG_LISTEN_FILE=$PG_CONF_DIR/conf.d/tippr-listen.conf
if [ "$TIPPR_ROLE" = "backend" ]; then
    pg_listen="listen_addresses = 'localhost,$TIPPR_BACKEND_LISTEN'"
else
    pg_listen=""
fi
pg_before=$(cat "$PG_LISTEN_FILE" "$PG_HBA" 2>/dev/null | md5sum)
if [ -n "$pg_listen" ]; then
    install -d -o postgres -g postgres "$PG_CONF_DIR/conf.d"
    echo "$pg_listen" > "$PG_LISTEN_FILE"
else
    rm -f "$PG_LISTEN_FILE"
fi
sed -i '/# tippr-frontends$/d' "$PG_HBA"
if [ "$TIPPR_ROLE" = "backend" ]; then
    echo "host tippr tippr $TIPPR_FRONTEND_ALLOW scram-sha-256 # tippr-frontends" >> "$PG_HBA"
fi
if [ "$(cat "$PG_LISTEN_FILE" "$PG_HBA" 2>/dev/null | md5sum)" != "$pg_before" ]; then
    echo "PostgreSQL: listening on ${TIPPR_BACKEND_LISTEN:-localhost} for $TIPPR_ROLE; restarting"
    systemctl restart postgresql
fi
