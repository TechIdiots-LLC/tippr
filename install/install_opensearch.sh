# Install OpenSearch 3.x as a single node listening on localhost only, for
# search_provider = opensearch.
###############################################################################
set -e

RUNDIR=$(dirname $0)
source $RUNDIR/install.cfg

OPENSEARCH_KEYRING=/etc/apt/keyrings/opensearch.gpg
OPENSEARCH_LIST=/etc/apt/sources.list.d/opensearch-3.x.list

if [ ! -s "$OPENSEARCH_KEYRING" ]; then
    install -d -m 0755 /etc/apt/keyrings
    curl -fsSL https://artifacts.opensearch.org/publickeys/opensearch-release.pgp \
        | gpg --dearmor --batch --yes -o "$OPENSEARCH_KEYRING"
fi
echo "deb [signed-by=$OPENSEARCH_KEYRING] https://artifacts.opensearch.org/releases/bundle/opensearch/3.x/apt stable main" \
    > "$OPENSEARCH_LIST"

if ! dpkg -s opensearch >/dev/null 2>&1; then
    apt-get update
    # The security plugin is disabled below (only local processes can reach
    # the port), so skip the package's demo security setup, which can fail
    # on its own (it did on GitHub's runners). Older packages ignore the
    # DISABLE_ settings and need an initial admin password instead; it's
    # never used.
    env DISABLE_INSTALL_DEMO_CONFIG=true DISABLE_SECURITY_PLUGIN=true \
        OPENSEARCH_INITIAL_ADMIN_PASSWORD="$(openssl rand -base64 24 | tr -d '/+=')Aa1!" \
        apt-get install $APTITUDE_OPTIONS opensearch
fi

# Our own config replaces the package's (and the security plugin's demo
# settings, which would need TLS on the port).
OPENSEARCH_YML=/etc/opensearch/opensearch.yml
if [ -f "$OPENSEARCH_YML" ] && ! grep -q "Generated by install/install_opensearch.sh" "$OPENSEARCH_YML"; then
    cp -a "$OPENSEARCH_YML" "$OPENSEARCH_YML.dist"
fi
cat > "$OPENSEARCH_YML" <<YML
# Generated by install/install_opensearch.sh -- changes are overwritten on
# reinstall. The package's original file is opensearch.yml.dist.
cluster.name: tippr
node.name: $(hostname -s)
path.data: /var/lib/opensearch
path.logs: /var/log/opensearch

# Only tippr on this machine talks to OpenSearch.
network.host: 127.0.0.1
http.port: 9200
discovery.type: single-node

plugins.security.disabled: true
YML
chown root:opensearch "$OPENSEARCH_YML"
chmod 0660 "$OPENSEARCH_YML"

install -d -m 0750 -g opensearch /etc/opensearch/jvm.options.d
cat > /etc/opensearch/jvm.options.d/tippr-heap.options <<HEAP
# Generated by install/install_opensearch.sh (TIPPR_OPENSEARCH_HEAP)
-Xms$TIPPR_OPENSEARCH_HEAP
-Xmx$TIPPR_OPENSEARCH_HEAP
HEAP

systemctl daemon-reload
systemctl enable opensearch
systemctl restart opensearch

echo "Waiting for OpenSearch to be available..."
for i in $(seq 1 120); do
    if curl -fsS http://127.0.0.1:9200/_cluster/health >/dev/null 2>&1; then
        echo "OpenSearch is up"
        exit 0
    fi
    sleep 1
done
echo "ERROR: OpenSearch did not start; see journalctl -u opensearch" >&2
exit 1
